import re
import sys

EXPECTED_ENTRIES = 193


def main(argv):
    if len(argv) != 2:
        print("usage: gen_ja_map.py <misaki ja.py>", file=sys.stderr)
        return 2
    with open(argv[1], encoding="utf-8") as f:
        src = f.read()
    entries = {}
    for m in re.finditer(r"^((?:chr\(\d+\)\+?)+): '([^']+)'", src, re.M):
        key = "".join(chr(int(n)) for n in re.findall(r"chr\((\d+)\)", m.group(1)))
        entries[key] = m.group(2)
    entries.update({"ッ": "ʔ", "ン": "ɴ", "ー": "ː"})
    if len(entries) != EXPECTED_ENTRIES:
        print(f"expected {EXPECTED_ENTRIES} entries, found {len(entries)}", file=sys.stderr)
        return 1
    print("// `mora_phonemes` is generated by scripts/gen_ja_map.py from misaki ja.py (Apache-2.0, hexgrad/misaki).")
    print("// Everything below it is hand-written.")
    print("pub(crate) fn mora_phonemes(mora: &str) -> Option<&'static str> {")
    print("    match mora {")
    for k in sorted(entries):
        print(f'        "{k}" => Some("{entries[k]}"),')
    print("        _ => None,")
    print("    }")
    print("}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
